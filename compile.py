#!/usr/bin/env python3
"""Amalgamates the pix sources into one single-header library.

    python compile.py                 -> dist/pix.h
    python compile.py -o other/pix.h  -> somewhere else
    python compile.py --test          -> also compile every example against the
                                         result with MSVC (or clang) to prove it

Starting from src/pix.h, every `#include "..."` is followed depth first, so a
module always lands after the modules it depends on and each file appears
once. Every module is split at its `#if defined(PIX_IMPLEMENTATION)` line:
all the API halves are emitted first, then all the implementation halves under
one guard. The result is used exactly like the modular sources:

    #define PIX_IMPLEMENTATION   // in exactly one .cpp
    #include "pix.h"
"""
import argparse
import datetime
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "src")
ENTRY = os.path.join(SRC, "pix.h")
LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')
IMPL_START = re.compile(r'^#if defined\(PIX_IMPLEMENTATION\)', re.M)


def collect(path, seen, order):
    """Depth-first walk of local includes; appends files in dependency order."""
    path = os.path.normpath(path)
    if path in seen:
        return
    seen.add(path)
    with open(path, encoding="utf-8") as f:
        text = f.read()
    for line in text.splitlines():
        m = LOCAL_INCLUDE.match(line)
        if m:
            collect(os.path.join(os.path.dirname(path), m.group(1)), seen, order)
    if path != os.path.normpath(ENTRY):
        order.append(path)


def strip_local_includes(text):
    return "\n".join(l for l in text.splitlines() if not LOCAL_INCLUDE.match(l))


def split(path):
    with open(path, encoding="utf-8") as f:
        text = strip_local_includes(f.read()).strip() + "\n"
    m = IMPL_START.search(text)
    if not m:
        return text, ""                  # header-only module (math, colliders, ...)
    api, impl = text[:m.start()], text[m.start():]
    # drop the "// ======" separator line that precedes each implementation
    api = re.sub(r'\n// =+\s*$', "\n", api.rstrip()) + "\n"
    return api, impl


def banner():
    with open(ENTRY, encoding="utf-8") as f:
        head = []
        for line in f:
            if not line.startswith("//"):
                break
            head.append(line.rstrip("\n"))
    stamp = datetime.date.today().isoformat()
    head += ["//", f"// Single-header build generated by compile.py on {stamp}.",
             "// Edit the modular sources under src/ and regenerate; do not edit this file."]
    return "\n".join(head) + "\n"


def amalgamate(out_path):
    order = []
    collect(ENTRY, set(), order)
    parts = [split(p) for p in order]
    rel = lambda p: os.path.relpath(p, SRC).replace("\\", "/")

    out = [banner(), "#ifndef PIX_SINGLE_HEADER_H", "#define PIX_SINGLE_HEADER_H", ""]
    for path, (api, _) in zip(order, parts):
        out += [f"// ---- {rel(path)} " + "-" * max(0, 70 - len(rel(path))), api]
    out += ["#endif // PIX_SINGLE_HEADER_H", "",
            "// " + "=" * 76, "// IMPLEMENTATION", "// " + "=" * 76,
            "#if defined(PIX_IMPLEMENTATION) && !defined(PIX_SINGLE_HEADER_IMPL)",
            "#define PIX_SINGLE_HEADER_IMPL", ""]
    for path, (_, impl) in zip(order, parts):
        if impl:
            out += [f"// ---- {rel(path)} " + "-" * max(0, 70 - len(rel(path))), impl]
    out += ["#endif // PIX_SINGLE_HEADER_IMPL", ""]

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    size = os.path.getsize(out_path)
    print(f"wrote {out_path}: {len(order)} modules, {size / 1024:.0f} KB")


def find_compiler():
    if shutil.which("cl"):
        return "cl"
    if shutil.which("clang++"):
        return "clang++"
    return None


def test(out_path):
    """Compiles each example, plus a two-file program, against the single header."""
    cc = find_compiler()
    if not cc:
        print("--test: no cl or clang++ on PATH (run from a VS developer prompt)")
        return False
    inc = os.path.dirname(os.path.abspath(out_path))
    build = os.path.join(ROOT, "build", "single_header_test")
    os.makedirs(build, exist_ok=True)

    # a second translation unit that only includes the API: proves the
    # declarations link against one implementation without duplicate symbols
    second = os.path.join(build, "second_tu.cpp")
    with open(second, "w") as f:
        f.write('#include "pix.h"\nfloat second_tu_len(vec3 v) { return v3len(v); }\n'
                'void second_tu_draw() { pix_draw_rect(0, 0, 1, 1, PIX_WHITE); }\n')

    sources = sorted(os.path.join(ROOT, "examples", n)
                     for n in os.listdir(os.path.join(ROOT, "examples")) if n.endswith(".cpp"))
    ok = True
    for i, src in enumerate(sources):
        name = os.path.splitext(os.path.basename(src))[0]
        exe = os.path.join(build, name + ".exe")
        files = [src] + ([second] if i == 0 else [])
        if cc == "cl":
            cmd = ["cl", "/nologo", "/std:c++14", "/EHsc", "/O2", "/W3", f"/I{inc}",
                   f"/Fe:{exe}", f"/Fo:{build}\\"] + files
        else:
            cmd = ["clang++", "-std=c++14", "-O2", "-Wall", f"-I{inc}", "-o", exe] + files
        r = subprocess.run(cmd, capture_output=True, text=True)
        problems = [l for l in (r.stdout + r.stderr).splitlines() if "error" in l or "warning" in l]
        status = "ok" if r.returncode == 0 and not problems else "FAILED"
        print(f"  {name:<14} {status}")
        for l in problems[:20]:
            print("    " + l)
        ok = ok and r.returncode == 0
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", default=os.path.join(ROOT, "dist", "pix.h"))
    ap.add_argument("--test", action="store_true", help="compile the examples against the output")
    args = ap.parse_args()
    amalgamate(args.out)
    if args.test and not test(args.out):
        sys.exit(1)


if __name__ == "__main__":
    main()
